import { nowNPTIso } from "@/lib/npt/format-npt";
import type { ClearWindow } from "@/types/weather";

// Builds a mock 12-hour timeline starting at 5 AM NPT today
function mockTimeline(patterns: Array<"best" | "good" | "watch" | "cloudy" | "poor">) {
  const base = new Date(nowNPTIso().replace("+05:45", "Z"));
  // Round to today 5 AM NPT (UTC 23:15 previous day, but we'll just use offsets)
  const startHour = 5;
  return patterns.map((quality, i) => {
    const d = new Date(base);
    d.setUTCHours(startHour - 5, 45 + i * 60, 0, 0); // approximate NPT offset
    return {
      hour: d.toISOString().replace("Z", "+05:45"),
      quality,
      isDaylight: i >= 1, // daylight from 6 AM
      isSunrise: i === 1,
      isGoldenHour: i === 1 || i === 2,
    };
  });
}

